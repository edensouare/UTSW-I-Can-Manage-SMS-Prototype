const aliases = [
  [/risk factors?|diagnos/i,1], [/palliative|curative/i,2], [/treatment team|who.*(team|treat)/i,3],
  [/reconstruct|neck dissection|mouth surgery|laryngeal/i,4], [/pack|hospital stay|before.*surgery|barium/i,5],
  [/trach|cannula|suction|breathing tube/i,6], [/feeding tube|g[- ]?tube|ng[- ]?tube|nasogastric|gastrostomy/i,7],
  [/incision|drain|skin graft|wound|after.*surgery|lymphedema/i,8], [/radiation|chemo|dental/i,9],
  [/surviv|long.term/i,10]
];
const words = text => text.toLowerCase().match(/[a-z]{3,}/g)?.filter(w => !['how','the','your','with','and','can','for','what','are','introduction','managing','care','module','guide','about','have','help','cancer'].includes(w)) || [];
function guideReply(input) {
  const text = input.trim();
  const menu = () => modules.map(m => m.number + '. ' + m.title).join('\n') + '\nReply GUIDE and a number, or describe a topic.';
  if (/^(menu|help|guides?|modules?|hi|hello|start)$/i.test(text)) return menu();
  const number = text.match(/^(?:guide\s*|module\s*)?(\d+)$/i);
  const hits = aliases.filter(([pattern]) => pattern.test(text)).map(([,id]) => id);
  const expanded = text.replace(/\bclean(?:ing)?\b/gi,'cleaning').replace(/\bsuction\b/gi,'suctioning').replace(/\bpack(?:ing)?\b/gi,'hospitalization');
  const tokens = new Set(words(expanded));
  function score(title) { return [...new Set(words(title))].filter(w => tokens.has(w)).length; }
  const ranked = modules.map(m => ({m,score:Math.max(score(m.title),...m.decks.map(d => score(d.title)))})).sort((a,b)=>b.score-a.score);
  const candidates = number ? modules.filter(m=>m.number===Number(number[1])) :
    hits.length ? modules.filter(m=>hits.includes(m.number)) : ranked.filter(r=>r.score && r.score===ranked[0].score).map(r=>r.m);
  if (!candidates.length) return 'I couldn’t match that to a guide. Text MENU for topics. For a personal care question, contact your care team directly.';
  if (candidates.length>1) return 'Which guide did you mean?\n'+candidates.map(m=>'GUIDE '+m.number+' — '+m.title).join('\n');
  const m=candidates[0];
  const decks=m.decks.map(d=>({d,score:score(d.title)})).sort((a,b)=>b.score-a.score);
  const direct = decks.length===1 || (decks[0].score>0 && decks[0].score>decks[1].score);
  return 'Guide '+m.number+' — '+m.title+(m.draft?' (in progress)':'')+'\n'+(direct?decks[0].d.title+'\n'+decks[0].d.url:'Browse the slide decks:\n'+m.folder);
}
if (typeof module !== 'undefined') module.exports = {guideReply, modules};
